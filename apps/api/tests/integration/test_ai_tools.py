def test_department_scope_and_dto_minimisation(ai):
    from app.models import (
        Role,
        Membership,
        Department,
        Task,
        CustomRole,
        CustomRolePermission,
        Permission,
    )

    with ai["owner"]() as db:
        own = Department(lodge_id=ai["lodge"].id, name="Own")
        foreign = Department(lodge_id=ai["lodge"].id, name="Hidden")
        db.add_all([own, foreign])
        db.flush()
        base = db.scalar(select(Role).where(Role.key == "department_manager"))
        custom = CustomRole(
            lodge_id=ai["lodge"].id,
            name="Scoped AI",
            base_role_id=base.id,
            is_active=True,
        )
        db.add(custom)
        db.flush()
        for key in ["ai.use", "tasks.view"]:
            db.add(
                CustomRolePermission(
                    lodge_id=ai["lodge"].id,
                    custom_role_id=custom.id,
                    permission_id=db.scalar(
                        select(Permission.id).where(Permission.key == key)
                    ),
                )
            )
        member = db.scalar(
            select(Membership).where(Membership.user_id == ai["user"].id)
        )
        member.role_id = base.id
        member.custom_role_id = custom.id
        member.department_id = own.id
        for title, dep in [("Visible task", own.id), ("Secret task", foreign.id)]:
            db.add(
                Task(
                    lodge_id=ai["lodge"].id,
                    title=title,
                    department_id=dep,
                    description="Private email owner@example.com",
                    created_by_user_id=ai["user"].id,
                )
            )
        db.commit()
    cid = create(ai)
    reply = ai["client"].post(
        ai["base"] + f"/conversations/{cid}/messages",
        json={"request_id": str(uuid4()), "content": "Which tasks?"},
        headers=ai["csrf"],
    )
    assert reply.status_code == 200, reply.text
    payload = ai["provider"].calls[1][0][-1]["content"]
    assert (
        "Visible task" in payload
        and "Secret task" not in payload
        and "description" not in payload
        and "owner@example.com" not in payload
    )
    names = [item["function"]["name"] for item in ai["provider"].calls[0][1]]
    assert names == ["get_tasks"]


def test_entitlement_and_access_rechecked_between_model_rounds(ai):
    from app.models import LodgeEntitlementOverride
    from app.ai.routes import provider_dependency
    from app.main import app

    class RevokingProvider:
        def complete(self, messages, tools):
            with ai["owner"]() as db:
                db.get(
                    LodgeEntitlementOverride,
                    {"lodge_id": ai["lodge"].id, "feature_key": "ai"},
                ).enabled = False
                db.commit()
            return Completion(tool_calls=[ToolCall("stale", "get_tasks", {})])

    app.dependency_overrides[provider_dependency] = lambda: RevokingProvider()
    cid = create(ai)
    reply = ai["client"].post(
        ai["base"] + f"/conversations/{cid}/messages",
        json={"request_id": str(uuid4()), "content": "Tasks"},
        headers=ai["csrf"],
    )
    assert reply.status_code == 403, reply.text


def test_assigned_scope_cannot_use_lodge_wide_aggregates(ai):
    from app.models import (
        Role,
        Membership,
        Permission,
        CustomRole,
        CustomRolePermission,
        StaffProfile,
        Task,
    )

    with ai["owner"]() as db:
        base = db.scalar(select(Role).where(Role.key == "general_staff"))
        custom = CustomRole(
            lodge_id=ai["lodge"].id,
            name="Own work AI",
            base_role_id=base.id,
            is_active=True,
        )
        db.add(custom)
        db.flush()
        for key in ["ai.use", "tasks.view", "dashboard.view", "reports.view"]:
            db.add(
                CustomRolePermission(
                    lodge_id=ai["lodge"].id,
                    custom_role_id=custom.id,
                    permission_id=db.scalar(
                        select(Permission.id).where(Permission.key == key)
                    ),
                )
            )
        member = db.scalar(
            select(Membership).where(Membership.user_id == ai["user"].id)
        )
        member.role_id = base.id
        member.custom_role_id = custom.id
        own = StaffProfile(
            lodge_id=ai["lodge"].id, user_id=ai["user"].id, full_name="Own worker"
        )
        other = StaffProfile(lodge_id=ai["lodge"].id, full_name="Other worker")
        db.add_all([own, other])
        db.flush()
        for title, staff in [
            ("Own assigned task", own),
            ("Hidden assigned task", other),
        ]:
            db.add(
                Task(
                    lodge_id=ai["lodge"].id,
                    title=title,
                    assigned_staff_id=staff.id,
                    created_by_user_id=ai["user"].id,
                )
            )
        db.commit()
    cid = create(ai)
    response = ai["client"].post(
        ai["base"] + f"/conversations/{cid}/messages",
        json={"request_id": str(uuid4()), "content": "Tasks"},
        headers=ai["csrf"],
    )
    assert response.status_code == 200, response.text
    assert [x["function"]["name"] for x in ai["provider"].calls[0][1]] == ["get_tasks"]
    payload = ai["provider"].calls[1][0][-1]["content"]
    assert "Own assigned task" in payload and "Hidden assigned task" not in payload


