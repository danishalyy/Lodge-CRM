@pytest.mark.parametrize(
    "tool_name",
    [
        name
        for name, tool in REGISTRY.items()
        if tool.source_kind not in {"document", "group"}
    ],
)
def test_every_read_tool_is_authorised_and_executed(ai, tool_name):
    ai["provider"].replies = [
        Completion(tool_calls=[ToolCall("read", tool_name, {})]),
        Completion("Test-only summary of the executed tool"),
    ]
    cid = create(ai)
    reply = ai["client"].post(
        ai["base"] + f"/conversations/{cid}/messages",
        json={"request_id": str(uuid4()), "content": "Read authorised records"},
        headers=ai["csrf"],
    )
    assert reply.status_code == 200, reply.text
    assert reply.json()["sources"][0]["tool"] == tool_name
    # The source is generated by execution, not copied from the model's text.
    assert reply.json()["sources"][0]["lodge_id"] == str(ai["lodge"].id)


@pytest.mark.parametrize("tool_name", list(REGISTRY))
def test_every_tool_rejects_missing_permission(ai, tool_name):
    from app.models import Role, Permission, RolePermission, Membership

    tool = REGISTRY[tool_name]
    with ai["owner"]() as db:
        limited = Role(key="ai_limited_" + uuid4().hex, name="Limited AI")
        db.add(limited)
        db.flush()
        key = db.scalar(select(Permission.id).where(Permission.key == "ai.use"))
